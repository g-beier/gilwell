//  ScormBuilder.swift
//  gilwellSCROM
//
//  Builds the SCORM 1.2 package from the project: copies the runtime (HTML/CSS/JS/fonts embedded in the app),
//  generates js/data.js with the content and creates imsmanifest.xml.
//

import Foundation

nonisolated struct PackageFile {
    let path: String
    let data: Data
}

nonisolated enum ExportError: LocalizedError {
    case missingResource(String)
    case invalidContent
    case unknownTemplate(String)

    var errorDescription: String? {
        switch self {
        case .missingResource(let name):
            return "Template file not found inside the app: \(name). Check that the Runtime folder is in the app target."
        case .invalidContent:
            return "Could not convert the project content."
        case .unknownTemplate(let id):
            return id.isEmpty
                ? "Choose a template in the initial wizard before continuing."
                : "This project uses the template “\(id)”, which this version of the app does not recognize."
        }
    }
}

/// Locates the runtime files inside the app bundle, whether the folder is preserved or "flattened".
nonisolated enum RuntimeAssets {
    nonisolated private final class Anchor {}

    private static func allFiles() -> [URL] {
        let bundle = Bundle(for: Anchor.self)
        guard let root = bundle.resourceURL else { return [] }
        let manager = FileManager.default
        guard let it = manager.enumerator(at: root, includingPropertiesForKeys: [.isRegularFileKey]) else { return [] }
        var list: [URL] = []
        for baseCase in it {
            if let url = baseCase as? URL, (try? url.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile) == true {
                list.append(url)
            }
        }
        return list
    }

    static func data(from path: String) throws -> Data {
        let files = allFiles()
        let name = (path as NSString).lastPathComponent
        // 1) full path preserved (…/Runtime/css/style.css); 2) file name only, if Xcode flattened the folder.
        let candidate = files.first(where: { $0.path.hasSuffix("/" + path) })
            ?? files.first(where: { $0.lastPathComponent == name })
        guard let url = candidate else { throw ExportError.missingResource(path) }
        return try Data(contentsOf: url)
    }
}

nonisolated enum ScormBuilder {

    /// All the package files, ready to go into the ZIP or a folder.
    static func build(_ project: Project) throws -> [PackageFile] {
        guard let template = Templates.find(project.template) else {
            throw ExportError.unknownTemplate(project.template)
        }
        var files: [PackageFile] = []
        for path in template.runtimeFiles {
            let data = try RuntimeAssets.data(from: template.runtimeFolder + "/" + path)
            files.append(PackageFile(path: path, data: data))
        }
        files.append(PackageFile(path: "js/data.js", data: try dataJS(project)))
        files.append(PackageFile(path: "imsmanifest.xml",
                                        data: manifest(project, files: files.map(\.path))))
        return files
    }

    static func zip(_ project: Project) throws -> Data {
        var zip = ZipWriter()
        // The manifest must be at the root; the order of the other entries does not matter.
        let files = try build(project)
        if let manifest = files.first(where: { $0.path == "imsmanifest.xml" }) {
            zip.add(manifest.path, manifest.data)
        }
        for a in files where a.path != "imsmanifest.xml" {
            zip.add(a.path, a.data)
        }
        return zip.build()
    }

    /// Writes the unzipped package to `folder` (used by the preview).
    static func writeFolder(_ project: Project, in folder: URL) throws {
        let manager = FileManager.default
        try manager.createDirectory(at: folder, withIntermediateDirectories: true)
        for a in try build(project) {
            let destination = folder.appendingPathComponent(a.path)
            try manager.createDirectory(at: destination.deletingLastPathComponent(), withIntermediateDirectories: true)
            try a.data.write(to: destination, options: .atomic)
        }
    }

    // MARK: - js/data.js

    static func dataJS(_ project: Project) throws -> Data {
        // The runtime reads sections and blocks; the project's old format is converted here, at export time.
        let structure = project.structure
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        let json = try encoder.encode(structure)
        var output = Data("/* Generated by Gilwell SCORM. Do not edit by hand: changes are lost the next time you export. */\nvar STRUCTURE = ".utf8)
        output.append(json)
        output.append(Data(";\n".utf8))
        return output
    }

    // MARK: - imsmanifest.xml

    static func manifest(_ project: Project, files: [String]) -> Data {
        let title = escapeXML(project.content.title.isEmpty ? (Templates.find(project.template)?.defaultTitle ?? "SCORM Package") : project.content.title)
        let list = files
            .filter { $0 != "imsmanifest.xml" }
            .map { "      <file href=\"\(escapeXML($0))\"/>" }
            .joined(separator: "\n")
        let xml = """
        <?xml version="1.0" encoding="UTF-8"?>
        <manifest identifier="gilwell-\(UUID().uuidString.lowercased())" version="1.0"
                  xmlns="http://www.imsproject.org/xsd/imscp_rootv1p1p2"
                  xmlns:adlcp="http://www.adlnet.org/xsd/adlcp_rootv1p2"
                  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">
          <metadata>
            <schema>ADL SCORM</schema>
            <schemaversion>1.2</schemaversion>
          </metadata>
          <organizations default="org-1">
            <organization identifier="org-1">
              <title>\(title)</title>
              <item identifier="item-1" identifierref="res-1" isvisible="true">
                <title>\(title)</title>
              </item>
            </organization>
          </organizations>
          <resources>
            <resource identifier="res-1" type="webcontent" adlcp:scormtype="sco" href="index.html">
        \(list)
            </resource>
          </resources>
        </manifest>

        """
        return Data(xml.utf8)
    }

    private static func escapeXML(_ text: String) -> String {
        text
            .replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
    }

    /// Safe file name derived from the title (no accents or spaces).
    static func fileName(_ title: String, standard: String = "case-study") -> String {
        let simple = title.folding(options: [.diacriticInsensitive, .caseInsensitive], locale: Locale(identifier: "pt_BR"))
        var result = ""
        var lastWasDash = false
        for c in simple.lowercased() {
            if c.isASCII && (c.isLetter || c.isNumber) {
                result.append(c)
                lastWasDash = false
            } else if !lastWasDash && !result.isEmpty {
                result.append("-")
                lastWasDash = true
            }
        }
        while result.hasSuffix("-") { result.removeLast() }
        return result.isEmpty ? standard : String(result.prefix(60)) + "-scorm"
    }
}
