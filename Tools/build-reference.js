// Reference generator (Node) with the same logic as ScormBuilder.swift.
// Usage: node build-reference.js project.gilwell output-folder
const fs = require("fs"), path = require("path");
const [,, entry, output] = process.argv;
const runtime = path.join(__dirname, "..", "gilwellSCROM", "Templates", "CaseStudy", "Runtime");
const proj = JSON.parse(fs.readFileSync(entry, "utf8"));
const { convert, problems } = require("./convert-v2");
const structure = convert(proj);
const ps = problems(structure);
if (ps.length) { console.error("Problems:\n- " + ps.join("\n- ")); process.exit(1); }
const c = { title: structure.title };
fs.rmSync(output, { recursive: true, force: true });
function copy(rel) { fs.mkdirSync(path.dirname(path.join(output, rel)), { recursive: true }); fs.copyFileSync(path.join(runtime, rel), path.join(output, rel)); }
const files = ["index.html", "css/style.css", "js/scorm.js", "js/app.js",
  "fonts/poppins-400.woff2", "fonts/poppins-500.woff2", "fonts/poppins-600.woff2", "fonts/poppins-700.woff2",
  "fonts/krona-one-400.woff2", "fonts/LICENSE-Poppins-OFL.txt", "fonts/LICENSE-KronaOne-OFL.txt"];
files.forEach(copy);
fs.writeFileSync(path.join(output, "js/data.js"), "/* Generated by Gilwell SCORM. Do not edit by hand. */\nvar STRUCTURE = " + JSON.stringify(structure, null, 2) + ";\n");
const esc = s => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const all = files.concat(["js/data.js"]);
fs.writeFileSync(path.join(output, "imsmanifest.xml"),
`<?xml version="1.0" encoding="UTF-8"?>
<manifest identifier="gilwell-${Date.now()}" version="1.0"
          xmlns="http://www.imsproject.org/xsd/imscp_rootv1p1p2"
          xmlns:adlcp="http://www.adlnet.org/xsd/adlcp_rootv1p2"
          xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">
  <metadata><schema>ADL SCORM</schema><schemaversion>1.2</schemaversion></metadata>
  <organizations default="org-1">
    <organization identifier="org-1">
      <title>${esc(c.title)}</title>
      <item identifier="item-1" identifierref="res-1" isvisible="true"><title>${esc(c.title)}</title></item>
    </organization>
  </organizations>
  <resources>
    <resource identifier="res-1" type="webcontent" adlcp:scormtype="sco" href="index.html">
${all.map(f => `      <file href="${f}"/>`).join("\n")}
    </resource>
  </resources>
</manifest>
`);
console.log("package at", output, all.length + 1, "files");
